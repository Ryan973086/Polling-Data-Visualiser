SELECT
    country,
    end_date,
    pollster,
    sample_size,
    MAX(CASE WHEN party = 'AfD' THEN percentage END) AS AfD,
    MAX(CASE WHEN party = 'BSW' THEN percentage END) AS BSW,
    MAX(CASE WHEN party = 'FDP' THEN percentage END) AS FDP,
    MAX(CASE WHEN party = 'Grüne' THEN percentage END) AS "Grüne",
    MAX(CASE WHEN party = 'Linke' THEN percentage END) AS Linke,
    MAX(CASE WHEN party = 'SPD' THEN percentage END) AS SPD,
    MAX(CASE WHEN party = 'Union' THEN percentage END) AS "Union",
    MAX(CASE WHEN party = 'ACT' THEN percentage END) AS ACT,
    MAX(CASE WHEN party = 'GRN' THEN percentage END) AS GRN_NZ,
    MAX(CASE WHEN party = 'LAB' THEN percentage END) AS LAB_NZ,
    MAX(CASE WHEN party = 'NAT' THEN percentage END) AS NAT,
    MAX(CASE WHEN party = 'NZF' THEN percentage END) AS NZF,
    MAX(CASE WHEN party = 'TOP' THEN percentage END) AS TOP,
    MAX(CASE WHEN party = 'TPM' THEN percentage END) AS TPM,
    MAX(CASE WHEN party = 'Aliança.cat' THEN percentage END) AS "Aliança.cat",
    MAX(CASE WHEN party = 'BNG' THEN percentage END) AS BNG,
    MAX(CASE WHEN party = 'CCa' THEN percentage END) AS CCa,
    MAX(CASE WHEN party = 'EH Bildu' THEN percentage END) AS "EH Bildu",
    MAX(CASE WHEN party = 'ERC' THEN percentage END) AS ERC,
    MAX(CASE WHEN party = 'Junts' THEN percentage END) AS Junts,
    MAX(CASE WHEN party = 'PNV' THEN percentage END) AS PNV,
    MAX(CASE WHEN party = 'PP' THEN percentage END) AS PP,
    MAX(CASE WHEN party = 'PSOE' THEN percentage END) AS PSOE,
    MAX(CASE WHEN party = 'Podemos' THEN percentage END) AS Podemos,
    MAX(CASE WHEN party = 'SALF' THEN percentage END) AS SALF,
    MAX(CASE WHEN party = 'Sumar' THEN percentage END) AS Sumar,
    MAX(CASE WHEN party = 'UPN' THEN percentage END) AS UPN,
    MAX(CASE WHEN party = 'Vox' THEN percentage END) AS Vox,
    MAX(CASE WHEN party = 'Con' THEN percentage END) AS Con,
    MAX(CASE WHEN party = 'Grn' THEN percentage END) AS Grn_UK,
    MAX(CASE WHEN party = 'LD' THEN percentage END) AS LD,
    MAX(CASE WHEN party = 'Lab' THEN percentage END) AS Lab_UK,
    MAX(CASE WHEN party = 'PC' THEN percentage END) AS PC,
    MAX(CASE WHEN party = 'Ref' THEN percentage END) AS Ref,
    MAX(CASE WHEN party = 'SNP' THEN percentage END) AS SNP
FROM polls
GROUP BY country, end_date, pollster, sample_size
ORDER BY country, end_date, pollster;
